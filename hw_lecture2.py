# Словари для формирования числа прописью
# units хранит названия чисел от 0 до 19 - их удобно брать напрямую, тк в русском языке они не подчиняются общему правилу
units = {
    0: "ноль", 1: "один", 2: "два", 3: "три", 4: "четыре",
    5: "пять", 6: "шесть", 7: "семь", 8: "восемь", 9: "девять",
    10: "десять", 11: "одиннадцать", 12: "двенадцать", 13: "тринадцать",
    14: "четырнадцать", 15: "пятнадцать", 16: "шестнадцать",
    17: "семнадцать", 18: "восемнадцать", 19: "девятнадцать"
}
# тенс хранит названия десятков
tens = {
    2: "двадцать", 3: "тридцать", 4: "сорок", 5: "пятьдесят",
    6: "шестьдесят", 7: "семьдесят", 8: "восемьдесят", 9: "девяносто"
}

# Запрашиваем ввод у пользователя
user_input = input("Введите число от 0 до 99: ")

# Проверяем, что введена именно строка из цифр
if not user_input.isdigit():
    print("Вы должны ввести число")
else:
    number = int(user_input)

    # Проверяем диапазон
    if number < 0 or number > 99:
        print("Вы должны ввести число от 0 до 99")
    elif number < 20:
        # Числа от 0 до 19 — берём напрямую из словаря units
        print(units[number])
    else:
        # Числа от 20 до 99 — десятки + единицы
        tens_part = number // 10   # цифра десятков
        units_part = number % 10   # цифра единиц

        if units_part == 0:
            print(tens[tens_part])
        else:
            print(tens[tens_part], units[units_part])